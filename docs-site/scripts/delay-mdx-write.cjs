// Test-only scheduling fixture: retain real generator bytes, but pause its
// truncating server.ts write until Next exits. Never loaded by normal checks.
const fs = require('node:fs');
const promises = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
if (process.argv.includes('typegen')) {
  const target = path.resolve('.source/server.ts');
  const trace = process.env.MDX_SHUTDOWN_TRACE;
  if (!trace) throw new Error('Missing isolated fixture trace path');
  const append = (event, data = {}) => fs.appendFileSync(trace,
    JSON.stringify({event, pid: process.pid, time: process.hrtime.bigint().toString(), ...data}) + '\n');
  const write = promises.writeFile.bind(promises);
  const exit = process.exit.bind(process);
  let truncated = false;
  promises.writeFile = async function(file, data, ...args) {
    if (path.resolve(String(file)) !== target) return write(file, data, ...args);
    append('generated', {bytes: Buffer.byteLength(data),
      sha256: crypto.createHash('sha256').update(data).digest('hex'), source: String(data)});
    // writeFile's default mode also opens/truncates before writing. Holding the
    // generated bytes here selects a slow-write schedule without fake exports.
    await promises.open(file, 'w');
    truncated = true;
    append('truncated', {bytes: fs.statSync(target).size});
    await new Promise(() => {});
  };
  process.exit = function(code) {
    const deadline = Date.now() + 5000;
    const finish = () => {
      if (truncated) {
        append('exit', {code, pending: true, bytes: fs.statSync(target).size});
        exit(code);
      } else if (Date.now() >= deadline) {
        append('fixture_timeout');
        exit(91);
      } else setTimeout(finish, 5);
    };
    // Explicit controlled interleaving: wait only for the real generator to
    // reach truncate, then forward Next's original exit. Bound failure at 5s.
    finish();
  };
}
