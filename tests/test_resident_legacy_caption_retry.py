UID = "usr_synthetic"


@pytest.mark.parametrize("content_type", ["image", "file"])
@pytest.mark.parametrize("with_caption", [False, True])
@pytest.mark.parametrize("omitted", [False, True])
def test_legacy_attachment_history_projects_caption_only(monkeypatch, content_type, with_caption, omitted):
    doc = dict(id="attachment", seq=1, ts=1001.0, role="user", content_type=content_type,
               owner_user_id=UID, visibility="shared", source="chat",
               body="legacy-attachment-bytes\nnot-caption", body_ct_len=529184,
               reply_status="replied")
    if with_caption:
        doc["caption"] = dict(body="legacy nested caption", id="cap", owner_user_id=UID, visibility="shared")
    attachment = chat_service._chat_history_item(doc, include_image_body=False)
    text = chat_service._chat_history_item(dict(id="text", seq=2, ts=1002.0, role="user",
        owner_user_id=UID, body="hello", content_type="text", visibility="shared"), include_image_body=False)
    page_attachment = dict(attachment)
    if omitted:
        page_attachment.pop("body", None)
        page_attachment["body_omitted"] = True
    requests = []

    def handle(request):
        requests.append(request.url.path)
        if request.url.path == "/v1/chat/history":
            return httpx.Response(200, json={"messages": [page_attachment, text]})
        assert omitted and request.url.path == "/v1/chat/messages/attachment/body"
        return httpx.Response(200, json={"message": attachment})

    with httpx.Client(transport=httpx.MockTransport(handle)) as client:
        monkeypatch.setattr(crc, "_HTTP", client)
        token = crc._RECALL_OPERATION_ACCOUNT.set((UID, "off"))
        try:
            rows = crc.get_decrypted_history(0)
            assert rows[0]["content"] == ""
            assert rows[1]["content"] == "hello"
            transcript = crc._recent_chat_context_for_foreground(before_ts=2000.0, before_seq=3)
        finally:
            crc._RECALL_OPERATION_ACCOUNT.reset(token)
    assert "hello" in transcript
    assert "legacy-attachment-bytes" not in transcript
    assert "legacy nested caption" not in transcript
    if content_type == "image":
        assert "[image]" in transcript and "io_cli chat-image --id attachment" in transcript
    if omitted:
        assert "/v1/chat/messages/attachment/body" in requests


def test_recall_failures_back_off_cap_and_reset_after_success(monkeypatch):
    from test_backlog_collapse import _neutralize_pipeline
    calls, replies, sleeps, events = [], [], [], []
    _neutralize_pipeline(monkeypatch, calls, replies)
    monkeypatch.setattr(crc, "_seen_ids", set())
    monkeypatch.setattr(crc, "_seen_ids_order", [])
    monkeypatch.setattr(crc.time, "sleep", sleeps.append)
    monkeypatch.setattr(crc, "_foreground_history_injection_enabled", lambda: False)
    monkeypatch.setattr(crc, "_emit_debug_trace", lambda *a, **kw: events.append((a, kw)))
    # Failure is generated by the real authenticated identity reader, not a
    # substituted recall helper. A successful turn uses the real selection path.
    healthy = False

    def handle(request):
        if request.url.path == "/v1/users/whoami":
            return httpx.Response(200, json={"user_id": UID, "content_encryption_effective": "off"}) if healthy else httpx.Response(503)
        if request.url.path == "/v1/memory/turn-selection":
            import json
            payload = json.loads(request.content)
            return httpx.Response(503, json={"category": "recall_unavailable", "detail": "local_disabled",
                "user_id": UID, "seq": payload["seq"], "message_id": payload["message_id"], "required_references": []})
        pytest.fail("unexpected request " + request.url.path)

    backoff = crc._RecallRetryBackoff()
    msg = dict(id="retry", seq=1, ts=time.time(), role="user", source="chat", content="hello",
               body="hello", content_type="text", owner_user_id=UID, visibility="shared")
    with httpx.Client(transport=httpx.MockTransport(handle)) as client:
        monkeypatch.setattr(crc, "_HTTP", client)
        for _ in range(9):
            assert crc._process_messages([msg], recall_backoff=backoff) == 0
            assert "retry" not in crc._seen_ids
        assert sleeps == [5, 10, 20, 40, 80, 160, 300, 300, 300]
        assert not calls and not replies
        assert len([e for e in events if e[0][1] == "context.recall_failed"]) == 9
        healthy = True
        assert crc._process_messages([msg], recall_backoff=backoff) == msg["ts"]
        assert len(calls) == len(replies) == 1
        assert backoff.delay == 0
        healthy = False
        next_msg = {**msg, "id": "retry-next", "seq": 2, "ts": msg["ts"] + 1}
        assert crc._process_messages([next_msg], recall_backoff=backoff) == 0
        assert sleeps[-1] == 5
        assert len([e for e in events if e[0][1] == "context.recall_failed"]) == 10


